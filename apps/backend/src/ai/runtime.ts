/**
 * `LIMN_CLAUDE_PATH` → the Agent SDK's `pathToClaudeCodeExecutable`: run the user's own installed
 * `claude` instead of the SDK's bundled binary (and `limn ai install` then skips downloading it).
 * Opt-in only — the bundled binary is version-locked to the SDK; a different `claude` may not be.
 * Spread into every `query()` options object.
 */
export function claudeExecutableOptions(
  env: NodeJS.ProcessEnv = process.env,
): { pathToClaudeCodeExecutable?: string } {
  const raw = env.LIMN_CLAUDE_PATH?.trim();
  if (!raw) return {};
  return { pathToClaudeCodeExecutable: isAbsolute(raw) ? raw : resolve(raw) };
}
