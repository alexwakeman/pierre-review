const HERE = dirname(fileURLToPath(import.meta.url));

/**
 * Build a runtime over one data directory. The app uses the module-level default below; tests
 * build their own over temp directories.
 */
export function createAiRuntime(opts: AiRuntimeOptions = {}) {
  const env = opts.env ?? process.env;
  const dataDir = opts.dataDir ?? resolveDataDir(env);
  const runtimeDir = join(dataDir, 'ai-runtime');
  const workspaceFrom = opts.workspaceFrom ?? HERE;
  // src/ai/runtime.ts → apps/backend; dist/ai/runtime.js → the release root. Both hold the
  // package.json the pins are read from.
  const packageRoot = opts.packageRoot ?? resolve(HERE, '..', '..');

  let workspaceHasSdk: boolean | null = null;
  const workspaceReady = (): boolean => {
    if (workspaceHasSdk === null) {
      workspaceHasSdk =
        findPackageDir(AGENT_SDK, workspaceFrom) !== null &&
        findPackageDir('zod', workspaceFrom) !== null;
    }
    return workspaceHasSdk;
  };

  // ---- pins ----
  function pins(): AiRuntimePins | null {
    const fromManifest = readJson(join(packageRoot, 'package.json'))?.[AI_RUNTIME_MANIFEST_FIELD];
    const out: Partial<AiRuntimePins> = {};
    for (const name of AI_RUNTIME_PACKAGES) {
      let v: unknown =
        fromManifest && typeof fromManifest === 'object'
          ? (fromManifest as Record<string, unknown>)[name]
          : undefined;
      // A dev checkout has no manifest field: pin to what the workspace itself installed.
      if (v === undefined) v = installedVersion(findPackageDir(name, workspaceFrom));
      if (typeof v !== 'string' || !EXACT_VERSION.test(v)) return null;
      out[name] = v;
    }
    return out as AiRuntimePins;
  }

  /** The Codex CLI's exact pin (`limnAiRuntime['@openai/codex']`), or null when this copy lists none. */
  function codexPin(): string | null {
    const fromManifest = readJson(join(packageRoot, 'package.json'))?.[AI_RUNTIME_MANIFEST_FIELD];
    const v =
      fromManifest && typeof fromManifest === 'object'
        ? (fromManifest as Record<string, unknown>)[CODEX_PACKAGE]
        : undefined;
    return typeof v === 'string' && EXACT_VERSION.test(v) ? v : null;
  }

  /** The Codex CLI under `fromDir`: 'ready' at its pin, 'stale' at another, 'no_binary' without the
   *  platform program (an optional dependency npm may silently skip), 'absent' when not there. */
  function codexDirState(fromDir: string): 'ready' | 'absent' | 'stale' | 'no_binary' {
    const dir = findPackageDirIn(CODEX_PACKAGE, fromDir);
    const have = installedVersion(dir);
    if (!dir || !have) return 'absent';
    if (!codexBinaryIn(fromDir)) return 'no_binary';
    const want = codexPin();
    return want && want !== have ? 'stale' : 'ready';
  }

  /**
   * 'ready' when every package is installed at its pin; 'stale' when installed at another;
   * 'no_binary' when the JS is there but the Agent SDK's native `claude` program is not (and no
   * LIMN_CLAUDE_PATH stands in for it).
   */
  function runtimeDirState(): 'ready' | 'absent' | 'stale' | 'no_binary' {
    if (!existsSync(join(runtimeDir, 'package.json'))) return 'absent';
    const want = pins();
    let anyMissing = false;
    let anyMismatch = false;
    for (const name of AI_RUNTIME_PACKAGES) {
      const dir = findPackageDir(name, runtimeDir);
      const have = installedVersion(dir);
      if (!dir || !have || !esmEntryOf(dir, ENTRY_SUBPATH[name])) {
        // An install from before a later package existed still runs the agents: stale, not absent.
        if (AI_RUNTIME_LATER_PACKAGES.includes(name)) anyMismatch = true;
        else anyMissing = true;
      } else if (want && want[name] !== have) anyMismatch = true;
    }
    if (anyMissing) return 'absent';
    if (!binaryOk(runtimeDir)) return 'no_binary';
    return anyMismatch ? 'stale' : 'ready';
  }

  // ⚠ THE AGENT SDK'S NATIVE PROGRAM IS AN OPTIONAL DEPENDENCY (one package per platform), and npm
  // treats a failed optional dependency as NON-FATAL: a fetch error or a libc/cpu mismatch still
  // exits 0. An install made with LIMN_CLAUDE_PATH set skips it on purpose (`--omit=optional`), and
  // that variable can be unset later. Either way the JS loads and every run then fails with
  // "Claude Code executable not found" — so 'ready' requires the binary, unless the user's own
  // `claude` is configured right now.
  function binaryOk(fromDir: string): boolean {
    if (env.LIMN_CLAUDE_PATH?.trim()) return true;
    const sdkDir = findPackageDir(AGENT_SDK, fromDir);
    if (!sdkDir) return false;
    const exe = process.platform === 'win32' ? 'claude.exe' : 'claude';
    // The same candidates, in any order, the SDK itself tries (linux: glibc or musl).
    const base = `${AGENT_SDK}-${process.platform}-${process.arch}`;
    const names = process.platform === 'linux' ? [base, `${base}-musl`] : [base];
    return names.some((name) => {
      const dir = findPackageDir(name, sdkDir);
      return dir !== null && existsSync(join(dir, exe));
    });
  }

  // ---- status ----
  let inFlight: Promise<AiRuntimeInstallResult> | null = null;
  /** Does the running download include Codex? */
  let inFlightCodex = false;
  let lastCodexFailure: string | null = null;
  const listeners = new Set<(p: AiRuntimeInstallProgress) => void>();
  let lastFailure: string | null = null;

  function status(): AiRuntimeStatus {
    if (inFlight) return { runtime: 'installing', runtimeMessage: null };
    if (workspaceReady()) return { runtime: 'ready', runtimeMessage: null };
    const state = runtimeDirState();
    if (state === 'ready') return { runtime: 'ready', runtimeMessage: null };
    if (lastFailure) return { runtime: 'failed', runtimeMessage: lastFailure };
    if (state === 'no_binary') {
      return {
        runtime: 'absent',
        runtimeMessage:
          'The Claude Code program is missing from the AI download. Set up AI again, or set LIMN_CLAUDE_PATH to your own claude.',
      };
    }
    if (state === 'stale') {
      return {
        runtime: 'absent',
        runtimeMessage: 'Limn was updated. Set up AI again to get the matching version.',
      };
    }
    return { runtime: 'absent', runtimeMessage: null };
  }

  function codexOverride(): string | null {
    const raw = env.LIMN_CODEX_PATH?.trim();
    if (!raw) return null;
    return isAbsolute(raw) ? raw : resolve(raw);
  }

  /**
   * The Codex CLI's state. `LIMN_CODEX_PATH` (the reader's own `codex` native program) makes it
   * ready without a download — the same opt-in as LIMN_CLAUDE_PATH, version-unchecked.
   */
  function codexStatus(): AiRuntimeStatus {
    if (inFlight && inFlightCodex) return { runtime: 'installing', runtimeMessage: null };
    if (codexOverride()) return { runtime: 'ready', runtimeMessage: null };
    const state = existsSync(join(runtimeDir, 'package.json')) ? codexDirState(runtimeDir) : 'absent';
    if (state === 'ready') return { runtime: 'ready', runtimeMessage: null };
    if (lastCodexFailure) return { runtime: 'failed', runtimeMessage: lastCodexFailure };
    if (state === 'no_binary') {
      return {
        runtime: 'absent',
        runtimeMessage: 'The Codex program is missing from the AI download. Run: limn ai install codex',
      };
    }
    if (state === 'stale') {
      return { runtime: 'absent', runtimeMessage: 'Limn was updated. Set up Codex again: limn ai install codex' };
    }
    return { runtime: 'absent', runtimeMessage: null };
  }

  /** The Codex program to run, or null when Codex is not set up. */
  function codexBinary(): string | null {
    const override = codexOverride();
    if (override) return override;
    if (!existsSync(join(runtimeDir, 'package.json'))) return null;
    // 'stale' still runs (an older pin is a working CLI); "set up again" is the status's job.
    const state = codexDirState(runtimeDir);
    return state === 'ready' || state === 'stale' ? codexBinaryIn(runtimeDir) : null;
  }

  // ---- loading ----
  const loaded = new Map<string, Promise<unknown>>();

  function load<T>(spec: AiRuntimePackage): Promise<T> {
    const hit = loaded.get(spec);
    if (hit) return hit as Promise<T>;
    const p = (async () => {
      const order: Array<'workspace' | 'runtime'> = workspaceReady()
        ? ['workspace', 'runtime']
        : ['runtime', 'workspace'];
      for (const source of order) {
        if (source === 'workspace') {
          // Plain bare specifier: identical to the static imports this module replaced.
          const dir = findPackageDir(spec, workspaceFrom);
          if (dir && workspaceFrom === HERE) return (await import(specifierFor(spec))) as T;
          const entry = dir ? esmEntryOf(dir, ENTRY_SUBPATH[spec]) : null;
          if (entry) return (await import(pathToFileURL(entry).href)) as T;
        } else if (['ready', 'stale'].includes(runtimeDirState())) {
          const dir = findPackageDir(spec, runtimeDir);
          const entry = dir ? esmEntryOf(dir, ENTRY_SUBPATH[spec]) : null;
          if (entry) return (await import(pathToFileURL(entry).href)) as T;
        }
      }
      throw new AiRuntimeMissingError(spec);
    })();
    loaded.set(spec, p);
    // A miss must not be remembered: the reader may set AI up a minute later.
    p.catch(() => loaded.delete(spec));
    return p;
  }

  // ---- install ----
  function emit(p: AiRuntimeInstallProgress): void {
    for (const l of listeners) {
      try {
        l(p);
      } catch {
        /* a listener's failure is its own */
      }
    }
  }

  function install(
    onProgress?: (p: AiRuntimeInstallProgress) => void,
    installOpts: InstallOptions = {},
  ): Promise<AiRuntimeInstallResult> {
    if (onProgress) listeners.add(onProgress);
    const detach = (): void => {
      if (onProgress) listeners.delete(onProgress);
    };
    // Single-flight: a second press (or a second tab) joins the running download. ⚠ A press for
    // Codex while a Claude-only download runs joins it too; Codex then still reads 'absent' and the
    // next press downloads it.
    if (inFlight) return inFlight.finally(detach);
    const withCodex =
      (installOpts.providers ?? ['claude']).includes('codex') ||
      (existsSync(join(runtimeDir, 'package.json')) && findPackageDirIn(CODEX_PACKAGE, runtimeDir) !== null);
    inFlightCodex = withCodex;
    inFlight = runInstall(installOpts, withCodex).finally(() => {
      inFlight = null;
      inFlightCodex = false;
    });
    return inFlight.finally(detach);
  }

  async function runInstall(installOpts: InstallOptions, withCodex: boolean): Promise<AiRuntimeInstallResult> {
    const failWith = (message: string): AiRuntimeInstallResult => {
      lastFailure = message;
      if (withCodex) lastCodexFailure = message;
      emit({ phase: 'failed', message });
      return { ok: false, message };
    };

    const want = pins();
    if (!want) {
      return failWith(
        'This copy of Limn does not list which AI runtime versions to download. Update Limn and try again.',
      );
    }
    const codexWant = withCodex ? codexPin() : null;
    if (withCodex && !codexWant) {
      return failWith('This copy of Limn does not list which Codex version to download. Update Limn and try again.');
    }
    const dependencies: Record<string, string> = { ...want, ...(codexWant ? { [CODEX_PACKAGE]: codexWant } : {}) };
    const npm = installOpts.npm ?? resolveNpm(env);
    if (!npm) return failWith('npm was not found. Install Node.js with npm, then try again.');

    lastFailure = null;
    if (withCodex) lastCodexFailure = null;
    emit({
      phase: 'starting',
      message: withCodex
        ? 'Starting the one-time download (about 110 MB, plus the Codex program).'
        : 'Starting the one-time download (about 110 MB).',
    });

    const staging = `${runtimeDir}.staging-${process.pid}-${Date.now()}`;
    try {
      mkdirSync(staging, { recursive: true });
      writeFileSync(
        join(staging, 'package.json'),
        JSON.stringify(
          {
            name: 'limn-ai-runtime',
            private: true,
            description: 'The AI runtime Limn downloads on first use. Safe to delete; Limn can download it again.',
            dependencies,
          },
          null,
          2,
        ) + '\n',
      );
    } catch (err) {
      rmSync(staging, { recursive: true, force: true });
      return failWith(`Could not write to ${dataDir}: ${(err as Error).message}`);
    }

    const args = [
      ...npm.args,
      'install',
      '--prefix',
      staging,
      '--no-audit',
      '--no-fund',
      '--no-update-notifier',
      // None of the packages needs an install script, so none gets to run one.
      '--ignore-scripts',
      '--no-package-lock',
    ];
    // Using your own `claude`: skip the SDK's bundled ~110 MB binary (its optional dependencies).
    // ⚠ Not with Codex: its platform program is an optional dependency too, and npm cannot omit one
    // package's optionals and keep another's.
    if (env.LIMN_CLAUDE_PATH?.trim() && !withCodex) args.push('--omit=optional');

    const timeoutMs = installOpts.timeoutMs ?? 10 * 60_000;
    const exit = await spawnNpm(npm, args, {
      cwd: staging,
      env,
      timeoutMs,
      onLine: (line) => emit({ phase: 'downloading', message: line.slice(0, 200) }),
    });
    const tail = exit.tail;

    if (exit.error || exit.timedOut || exit.code !== 0) {
      rmSync(staging, { recursive: true, force: true });
      if (exit.error) return failWith(exit.error);
      if (exit.timedOut) {
        return failWith(
          `The download took longer than ${Math.round(timeoutMs / 60_000)} minutes and was stopped. Check your network and try again: limn ai install`,
        );
      }
      const last = tail.filter((l) => /err/i.test(l)).slice(-2).join(' ') || tail.slice(-1)[0] || '';
      return failWith(
        `The download failed (npm exit code ${exit.code}). Check your network or proxy and try again: limn ai install${last ? `. npm said: ${last.slice(0, 300)}` : ''}`,
      );
    }

    emit({ phase: 'verifying', message: 'Checking the download.' });
    for (const name of AI_RUNTIME_PACKAGES) {
      const dir = findPackageDir(name, staging);
      const have = installedVersion(dir);
      if (!dir || have !== want[name] || !esmEntryOf(dir, ENTRY_SUBPATH[name])) {
        rmSync(staging, { recursive: true, force: true });
        return failWith(
          `The download finished but ${name} ${want[name]} is missing from it. Try again: limn ai install`,
        );
      }
    }
    if (!binaryOk(staging)) {
      rmSync(staging, { recursive: true, force: true });
      return failWith(
        `The download finished but the Claude Code program for ${process.platform}-${process.arch} is missing from it. Try again: limn ai install. Or set LIMN_CLAUDE_PATH to your own claude.`,
      );
    }
    if (codexWant) {
      const codexDir = findPackageDirIn(CODEX_PACKAGE, staging);
      if (!codexDir || installedVersion(codexDir) !== codexWant) {
        rmSync(staging, { recursive: true, force: true });
        return failWith(`The download finished but ${CODEX_PACKAGE} ${codexWant} is missing from it. Try again: limn ai install codex`);
      }
      if (!codexBinaryIn(staging)) {
        rmSync(staging, { recursive: true, force: true });
        return failWith(
          `The download finished but the Codex program for ${process.platform}-${process.arch} is missing from it. Try again: limn ai install codex`,
        );
      }
    }

    // Swap in place: the previous runtime (if any) moves aside first, so a failure here leaves
    // either the old one or the new one — never half of each.
    const old = `${runtimeDir}.old-${process.pid}-${Date.now()}`;
    try {
      if (existsSync(runtimeDir)) renameSync(runtimeDir, old);
      renameSync(staging, runtimeDir);
    } catch (err) {
      if (!existsSync(runtimeDir) && existsSync(old)) renameSync(old, runtimeDir);
      rmSync(staging, { recursive: true, force: true });
      return failWith(`Could not finish setting up AI in ${runtimeDir}: ${(err as Error).message}`);
    }
    rmSync(old, { recursive: true, force: true });

    lastFailure = null;
    if (withCodex) lastCodexFailure = null;
    emit({ phase: 'done', message: withCodex ? 'AI is set up, with Codex.' : 'AI is set up.' });
    return { ok: true };
  }

  return { runtimeDir, pins, codexPin, status, codexStatus, codexBinary, load, install };
}

