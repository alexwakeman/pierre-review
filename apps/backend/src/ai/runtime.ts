// ---- package location (no exports-map surprises) ----------------------------------------------

function readJson(path: string): Record<string, unknown> | null {
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>;
  } catch {
    return null;
  }
}

/**
 * The package's directory as an ESM `import '<spec>'` from `fromDir` would find it: the nearest
 * `node_modules/<spec>` walking up the ancestors. ⚠ NOT `createRequire(...).resolve.paths()` — that
 * list also carries NODE_PATH and the global folders (`~/.node_modules`, `<prefix>/lib/node`),
 * which ESM ignores, so a package found there would be one the real import cannot see. (Under
 * pnpm/vitest NODE_PATH points into the workspace store, which is how this was found.)
 */
export function findPackageDir(spec: string, fromDir: string): string | null {
  let dir = resolve(fromDir);
  for (;;) {
    const candidate = join(dir, 'node_modules', spec);
    if (existsSync(join(candidate, 'package.json'))) {
      try {
        return realpathSync(candidate);
      } catch {
        return candidate;
      }
    }
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/**
 * A package INSIDE one install prefix only: `<prefix>/node_modules/<spec>`, with no walk up the
 * ancestors. ⚠ Codex is looked up this way: `findPackageDir` would happily return a Codex installed
 * in any parent folder (a project's own node_modules, a global prefix), which is not the program at
 * Limn's pin.
 */
export function findPackageDirIn(spec: string, prefix: string): string | null {
  const candidate = join(resolve(prefix), 'node_modules', spec);
  if (!existsSync(join(candidate, 'package.json'))) return null;
  try {
    return realpathSync(candidate);
  } catch {
    return candidate;
  }
}

/**
 * `findPackageDir`, but the walk STOPS at `stopAt` (inclusive): nothing above the install prefix is
 * looked at. For the Codex platform package, resolved from the CLI package's own directory the way
 * its bin/codex.js does (npm may nest it, or hoist it to the prefix). A `fromDir` outside `stopAt`
 * finds nothing.
 */
export function findPackageDirWithin(spec: string, fromDir: string, stopAt: string): string | null {
  const real = (p: string): string => {
    try {
      return realpathSync(p);
    } catch {
      return resolve(p);
    }
  };
  const stop = real(stopAt);
  let dir = real(fromDir);
  const rel = relative(stop, dir);
  if (rel === '..' || rel.startsWith(`..${sep}`) || isAbsolute(rel)) return null;
  for (;;) {
    const candidate = join(dir, 'node_modules', spec);
    if (existsSync(join(candidate, 'package.json'))) {
      try {
        return realpathSync(candidate);
      } catch {
        return candidate;
      }
    }
    if (dir === stop) return null;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

const ESM_CONDITIONS = new Set(['node', 'import', 'default']);

/** Walk one exports target with the ESM conditions, in the package's own key order. */
function pickTarget(target: unknown): string | null {
  if (typeof target === 'string') return target;
  if (Array.isArray(target)) {
    for (const t of target) {
      const hit = pickTarget(t);
      if (hit) return hit;
    }
    return null;
  }
  if (target && typeof target === 'object') {
    for (const [key, value] of Object.entries(target as Record<string, unknown>)) {
      if (!ESM_CONDITIONS.has(key)) continue;
      const hit = pickTarget(value);
      if (hit) return hit;
    }
  }
  return null;
}

/**
 * The file an ESM `import '<pkg>'` (or `'<pkg>/<subpath>'`) resolves to, given the package
 * directory. `subpath` is an exports key: '.' for the root, './server' for a subpath.
 */
export function esmEntryOf(pkgDir: string, subpath = '.'): string | null {
  const pkg = readJson(join(pkgDir, 'package.json'));
  if (!pkg) return null;
  const exp = pkg.exports;
  let rel: string | null = null;
  if (exp !== undefined) {
    const isSubpathMap =
      !!exp && typeof exp === 'object' && !Array.isArray(exp) &&
      Object.keys(exp as object).some((k) => k.startsWith('.'));
    if (isSubpathMap) rel = pickTarget((exp as Record<string, unknown>)[subpath]);
    else if (subpath === '.') rel = pickTarget(exp);
  } else if (subpath !== '.') {
    rel = subpath;
  }
  if (subpath === '.') {
    if (!rel && typeof pkg.module === 'string' && pkg.type === 'module') rel = pkg.module;
    if (!rel && typeof pkg.main === 'string') rel = pkg.main;
    if (!rel) rel = 'index.js';
  }
  if (!rel) return null;
  const file = resolve(pkgDir, rel);
  return existsSync(file) ? file : null;
}

export function installedVersion(pkgDir: string | null): string | null {
  if (!pkgDir) return null;
  const v = readJson(join(pkgDir, 'package.json'))?.version;
  return typeof v === 'string' ? v : null;
}

// ---- npm (shared with ml/runtime.ts, which installs its own first-use packages the same way) ----

export interface NpmCommand {
  command: string;
  args: string[];
}

/**
 * npm's own JS entry run with THIS node, so there is no shell and no PATH guessing on Windows
 * (where `npm` is a .cmd that cannot be spawned without one).
 */
export function resolveNpm(env: NodeJS.ProcessEnv = process.env): NpmCommand | null {
  const viaEnv = env.npm_execpath;
  if (viaEnv && /npm-cli\.c?js$/.test(viaEnv) && existsSync(viaEnv)) {
    return { command: process.execPath, args: [viaEnv] };
  }
  const nodeDir = dirname(process.execPath);
  for (const candidate of [
    join(nodeDir, '..', 'lib', 'node_modules', 'npm', 'bin', 'npm-cli.js'),
    join(nodeDir, 'node_modules', 'npm', 'bin', 'npm-cli.js'),
  ]) {
    if (existsSync(candidate)) return { command: process.execPath, args: [candidate] };
  }
  if (process.platform !== 'win32') return { command: 'npm', args: [] };
  return null;
}

export interface NpmExit {
  code: number | null;
  error: string | null;
  timedOut: boolean;
  /** The last few non-empty output lines, for the failure message. */
  tail: string[];
}

/** Run one npm command to completion. Never throws; a spawn failure comes back as `error`. */
export function spawnNpm(
  npm: NpmCommand,
  args: string[],
  opts: { cwd: string; env: NodeJS.ProcessEnv; timeoutMs: number; onLine?: (line: string) => void },
): Promise<NpmExit> {
  const tail: string[] = [];
  return new Promise<NpmExit>((done) => {
    let child: ChildProcess;
    try {
      child = spawn(npm.command, args, {
        cwd: opts.cwd,
        env: { ...opts.env, npm_config_loglevel: 'http' },
        stdio: ['ignore', 'pipe', 'pipe'],
        shell: false,
        windowsHide: true,
      });
    } catch (err) {
      done({ code: null, error: (err as Error).message, timedOut: false, tail });
      return;
    }
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill('SIGTERM');
    }, opts.timeoutMs);
    const onData = (buf: Buffer): void => {
      for (const raw of buf.toString('utf8').split(/\r?\n/)) {
        const line = raw.trim();
        if (!line) continue;
        tail.push(line);
        if (tail.length > 8) tail.shift();
        opts.onLine?.(line);
      }
    };
    child.stdout?.on('data', onData);
    child.stderr?.on('data', onData);
    child.on('error', (err: NodeJS.ErrnoException) => {
      clearTimeout(timer);
      done({
        code: null,
        error: err.code === 'ENOENT' ? 'npm was not found. Install Node.js with npm, then try again.' : err.message,
        timedOut: false,
        tail,
      });
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      done({ code, error: null, timedOut, tail });
    });
  });
}

// ---- the Codex program --------------------------------------------------------------------------

/** Codex's platform packages and their target triples — as `@openai/codex`'s own bin/codex.js
 *  (0.164.0) maps them. Limn does not run that wrapper: it starts the native program directly. */
const CODEX_TARGETS: Record<string, { pkg: string; triple: string }> = {
  'linux-x64': { pkg: '@openai/codex-linux-x64', triple: 'x86_64-unknown-linux-musl' },
  'linux-arm64': { pkg: '@openai/codex-linux-arm64', triple: 'aarch64-unknown-linux-musl' },
  'darwin-x64': { pkg: '@openai/codex-darwin-x64', triple: 'x86_64-apple-darwin' },
  'darwin-arm64': { pkg: '@openai/codex-darwin-arm64', triple: 'aarch64-apple-darwin' },
  'win32-x64': { pkg: '@openai/codex-win32-x64', triple: 'x86_64-pc-windows-msvc' },
  'win32-arm64': { pkg: '@openai/codex-win32-arm64', triple: 'aarch64-pc-windows-msvc' },
};

/**
 * The Codex native program under an install prefix (`<fromDir>/node_modules/@openai/codex` and its
 * platform package, wherever npm put it), or null. The platform package is resolved FROM the CLI
 * package's own directory, the way its bin/codex.js does.
 */
export function codexBinaryIn(
  fromDir: string,
  platform: string = process.platform,
  arch: string = process.arch,
): string | null {
  const target = CODEX_TARGETS[`${platform}-${arch}`];
  if (!target) return null;
  // ⚠ Only INSIDE the prefix: never a Codex (or its platform program) from a parent folder.
  const cliDir = findPackageDirIn(CODEX_PACKAGE, fromDir);
  if (!cliDir) return null;
  const exe = platform === 'win32' ? 'codex.exe' : 'codex';
  const platformDir = findPackageDirWithin(target.pkg, cliDir, fromDir);
  for (const vendorRoot of [platformDir ? join(platformDir, 'vendor') : null, join(cliDir, 'vendor')]) {
    if (!vendorRoot) continue;
    const file = join(vendorRoot, target.triple, 'bin', exe);
    if (existsSync(file)) return file;
  }
  return null;
}

