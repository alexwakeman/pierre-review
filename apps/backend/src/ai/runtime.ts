// THE AI RUNTIME LOADER — the ONE module allowed to import an AI SDK.
//
// Claude Review, the review chat and AI Fix are free and ship in the public npm package, but the
// SDKs they run on do NOT: `@anthropic-ai/claude-agent-sdk` pulls a native `claude` binary of
// ~110 MB to download (~240 MB unpacked) per platform, against a ~18 MB package. Putting it in
// `dependencies` (or `optionalDependencies`, which npm installs by default and a dependent package
// cannot switch off under `npx`) would make every `npx limn-review` fifteen times heavier for
// people who never press a Review button. So the four packages are INSTALLED ON FIRST USE:
//
//   @anthropic-ai/claude-agent-sdk · @anthropic-ai/sdk · @modelcontextprotocol/sdk · zod
//
// (plus the reference-docs converters — mammoth · turndown · turndown-plugin-gfm — which ride the
// same download because only an agentic feature uses them; see AI_RUNTIME_LATER_PACKAGES)
//
// at EXACT pinned versions into `<dataDir>/ai-runtime` (`~/.limn/ai-runtime`), by
// `npm install --prefix`, after the reader presses "Set up AI" or runs `limn ai install`. The pins
// ride the release manifest as a NON-dependency field (`limnAiRuntime`), generated by
// scripts/build-release.mjs from what the workspace actually installed — so a user downloads the
// versions the test suite ran against.
//
// ⚠ HOW A MODULE OUTSIDE OUR OWN node_modules IS LOADED. A bare specifier in ESM cannot see another
// prefix and NODE_PATH does not apply to ESM, so each package is located by walking
// `<dir>/node_modules` the way ESM resolution does, and then imported by FILE URL. The entry
// is picked with the ESM conditions (`node`, `import`, `default`), NEVER `require.resolve`: zod
// publishes `index.cjs` under `require` and `index.js` under `import`, and the SDK's own
// `import 'zod'` takes the ESM one. Loading the CJS twin would give our tool schemas a SECOND zod
// instance, which silently breaks the SDK's schema conversion. Same install, same conditions,
// same instance — the test pins it.
//
// ⚠ DEV IS UNCHANGED. When the workspace's own node_modules resolve the Agent SDK (`pnpm dev`, the
// test suite), everything loads by plain bare specifier exactly as the static imports did, and no
// runtime directory is consulted first. The cloud image is the third case: it ships
// `@anthropic-ai/sdk` as a real dependency (`--with-pro`, for the metered summary path) and no
// Agent SDK, so a package missing from one source falls through to the other.
//
// ⚠ CODEX (docs/CODEX-PLAN.md § 3.7): `@openai/codex` — the Codex CLI and its native program per
// platform — rides the SAME runtime directory, but ONLY when the reader asks for it ("Set up AI" with
// Codex, `limn ai install codex`). It is never imported: Limn runs its native program directly
// (`codexBinaryPath`), located here, the one module that knows where the runtime lives. Its pin is
// `limnAiRuntime['@openai/codex']`, DECLARED in apps/backend/package.json's own `limnAiRuntime`
// (the CLI is not a workspace dependency — 360 MB unpacked in every dev checkout) and copied into
// the release manifest by scripts/build-release.mjs. An install keeps Codex if it is already there,
// so re-running "Set up AI" for Claude never removes it.
//
// ⚠ NOTHING ELSE MAY IMPORT THESE PACKAGES. Type-only imports are fine (erased at emit); a value
// import anywhere else fails with ERR_MODULE_NOT_FOUND on an npm install — and only when someone
// clicks the feature. scripts/build-release.mjs greps the emitted JS and fails the build on one.
